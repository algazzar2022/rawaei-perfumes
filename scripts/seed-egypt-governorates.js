async function seed() {
  console.log('Clearing old shipping methods...');
  await prisma.shippingMethod.deleteMany({});

  console.log('Seeding 27 Egyptian Governorates...');
  for (const gov of governorates) {
    await prisma.shippingMethod.create({
      data: gov,
    });
  }

  const count = await prisma.shippingMethod.count();
  console.log(`Successfully seeded ${count} governorates of Egypt into database.`);
}

seed()
  .catch((e) => {
    console.error('Error seeding governorates:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
